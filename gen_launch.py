#!/usr/bin/env python3
# Generates LaunchSpeedup.inc — 每个候选各持独立 orig IMP 的 duration hook。
#
# ★ 1.0.4 起只保留【无参数】候选。
#   带参数的 selector（如 _completionDurationForContext:）需要知道参数的精确类型
#   才能正确调用原实现；类型猜错 = 毁栈 = SpringBoard 崩溃，而且 @try 抓不到。
#   无参 candidate 仍然有「返回值是 double 还是 CGFloat/void」的不确定性，
#   但风险显著低一些（且调用点少）。这也是为什么 gLaunchSpeedup 默认关闭。

CANDIDATES = [
    # (className, selectorString)   —— 全部无参
    ("SBAppLaunchAnimationController",        "animationDuration"),
    ("SBAppLaunchAnimationController",        "duration"),
    ("SBAppLaunchAnimationController",        "_duration"),
    ("SBAppTransition",                       "duration"),
    ("SBAppTransition",                       "_completionDuration"),
    ("SBAppTransition",                       "completionDuration"),
    ("SBAppToAppWorkspaceTransaction",        "completionDuration"),
    ("SBAppToAppWorkspaceTransaction",        "duration"),
    ("SBAppToHomeWorkspaceTransaction",       "completionDuration"),
    ("SBAppToHomeWorkspaceTransaction",       "duration"),
    ("SBAppActivationWorkspaceTransaction",   "completionDuration"),
    ("SBAppDeactivationWorkspaceTransaction", "completionDuration"),
    ("SBApplicationLaunchTransition",         "duration"),
    ("SBAppLaunchTransition",                 "duration"),
]

out = []
out.append("// AUTO-GENERATED by gen_launch.py — do not edit.")
out.append("#import <objc/runtime.h>")
out.append("#import <objc/message.h>")
out.append("")
out.append("extern void MSHookMessageEx(Class _cls, SEL _sel, IMP _new, IMP *_orig);")
out.append("")

for i, (cls, sel) in enumerate(CANDIDATES):
    out.append("static IMP _orig_%d = NULL;" % i)
    out.append("static double _lhook_%d(id self, SEL _cmd) {" % i)
    out.append("    double d = _orig_%d ? ((double(*)(id,SEL))_orig_%d)(self,_cmd) : 0.0;" % (i, i))
    out.append("    if (gLaunchSpeedup && d > 0.0 && gLaunchDivisor > 0.0) d /= gLaunchDivisor;")
    out.append("    return d;")
    out.append("}")
    out.append("")

out.append("static int installLaunchSpeedupHooks(void) {")
out.append("    if (!gLaunchSpeedup || gSafeMode) return 0;")
out.append("    int n = 0;")
for i, (cls, sel) in enumerate(CANDIDATES):
    out.append("    {")
    out.append('        Class c = objc_getClass("%s");' % cls)
    out.append('        SEL s = sel_registerName("%s");' % sel)
    out.append("        if (c && [c instancesRespondToSelector:s]) {")
    out.append("            MSHookMessageEx(c, s, (IMP)_lhook_%d, &_orig_%d);" % (i, i))
    out.append("            n++;")
    out.append('            rawLog("launch-hook: %s :: %s");' % (cls, sel))
    out.append("        }")
    out.append("    }")
out.append("    return n;")
out.append("}")

print("\n".join(out))

#!/usr/bin/env python3
# Generates LaunchSpeedup.inc — 通过公开的 UIView 动画 API 加速启动动画。
#
# ★ 1.0.6 之前的方案彻底废弃：
#   探测结果显示 iOS 17.3.1 的 SpringBoard 里根本没有任何带 duration 的 SBApp* 类
#   （objc_getClassList 扫了 90071 个类，0 命中）。那套类名是旧 iOS 的，猜不出来。
#
# ★ 新方案：hook UIView 的公开动画 API。
#   App 启动动画（图标放大、内容淡入）本质都是 UIView 动画，SpringBoard 也是用它实现的。
#   这些方法签名在 UIView.h 里写得一清二楚，不存在 ABI 猜测风险 —— 这正是
#   1.0.4 崩溃（结构体强转 objc_msgSend）之后必须坚持的原则。
#
# ★ 只加速「长动画」，不碰短动画：
#   0.05s 的按钮反馈除以 3 会变成 0.016s，可能导致动画被跳过或视觉闪烁。
#   设一个下限阈值（MIN_DURATION），只有超过它的才加速。

MIN_DURATION = 0.12   # 秒。低于这个值的动画不加速（按钮点击之类的反馈）
DIVISOR_SYM   = "gLaunchDivisor"

out = []
out.append("// AUTO-GENERATED by gen_launch.py — do not edit.")
out.append("// 通过公开 UIView 动画 API 加速。签名全部来自 UIView.h，无 ABI 猜测。")
out.append("#import <UIKit/UIKit.h>")
out.append("")
out.append("// 低于此值的动画不加速（按钮反馈等短动画）")
out.append("#define kMinAccelDuration %sf" % MIN_DURATION)
out.append("")
out.append("static NSTimeInterval accel(NSTimeInterval d) {")
out.append("    // ★ 只作用于 SpringBoard。不加这行的话，所有 App 的所有动画都会被加速——")
out.append("    //   那不只是启动变快，整个系统的动效都会变形。")
out.append("    if (!isSB()) return d;")
out.append("    if (!gLaunchSpeedup || gSafeMode) return d;")
out.append("    if (d < kMinAccelDuration) return d;          // 短动画不碰")
out.append("    if (%s <= 1.0) return d;" % DIVISOR_SYM)
out.append("    return d / %s;" % DIVISOR_SYM)
out.append("}")
out.append("")

HOOKS = [
    ("animateWithDuration:animations:",
     "- (void)animateWithDuration:(NSTimeInterval)duration animations:(void (^)(void))animations",
     "- (void)animateWithDuration:(NSTimeInterval)duration animations:(void (^)(void))animations {",
     "    %orig(accel(duration), animations);"),
    ("animateWithDuration:animations:completion:",
     "- (void)animateWithDuration:(NSTimeInterval)duration animations:(void (^)(void))animations completion:(void (^)(BOOL))completion",
     "- (void)animateWithDuration:(NSTimeInterval)duration animations:(void (^)(void))animations completion:(void (^)(BOOL))completion {",
     "    %orig(accel(duration), animations, completion);"),
    ("animateWithDuration:delay:options:animations:completion:",
     "- (void)animateWithDuration:(NSTimeInterval)duration delay:(NSTimeInterval)delay options:(UIViewAnimationOptions)options animations:(void (^)(void))animations completion:(void (^)(BOOL))completion",
     "- (void)animateWithDuration:(NSTimeInterval)duration delay:(NSTimeInterval)delay options:(UIViewAnimationOptions)options animations:(void (^)(void))animations completion:(void (^)(BOOL))completion {",
     "    %orig(accel(duration), delay, options, animations, completion);"),
    ("animateKeyframesWithDuration:delay:options:animations:completion:",
     "- (void)animateKeyframesWithDuration:(NSTimeInterval)duration delay:(NSTimeInterval)delay options:(UIViewKeyframeAnimationOptions)options animations:(void (^)(void))animations completion:(void (^)(BOOL))completion",
     "- (void)animateKeyframesWithDuration:(NSTimeInterval)duration delay:(NSTimeInterval)delay options:(UIViewKeyframeAnimationOptions)options animations:(void (^)(void))animations completion:(void (^)(BOOL))completion {",
     "    %orig(accel(duration), delay, options, animations, completion);"),
]

out.append("static int installLaunchSpeedupHooks(void) {")
out.append("    if (!gLaunchSpeedup || gSafeMode) return 0;")
out.append("    int n = 0;")
out.append("    // 只装签名在 SDK 里确认过的方法；类不存在就跳过（防御性）")
out.append('    Class uiv = objc_getClass("UIView");')
out.append("    if (!uiv) { rawLog(\"launch-speedup: UIView not found\"); return 0; }")
for sel, decl, _, _ in HOOKS:
    out.append("    if ([uiv respondsToSelector:@selector(%s)]) {" % sel)
    out.append("        n++;")
    out.append('        rawLog("launch-hook: UIView :: %s");' % sel)
    out.append("    }")
out.append("    return n;")
out.append("}")
out.append("")
SIGS = [
    # (selector, C 类型串, 形参声明, 调用实参)
    ("animateWithDuration:animations:",
     "void(*)(id,SEL,NSTimeInterval,void*)",
     "id self, SEL _cmd, NSTimeInterval duration, void *anim",
     "accel(duration), anim"),
    ("animateWithDuration:animations:completion:",
     "void(*)(id,SEL,NSTimeInterval,void*,void*)",
     "id self, SEL _cmd, NSTimeInterval duration, void *anim, void *completion",
     "accel(duration), anim, completion"),
    ("animateWithDuration:delay:options:animations:completion:",
     "void(*)(id,SEL,NSTimeInterval,NSTimeInterval,NSUInteger,void*,void*)",
     "id self, SEL _cmd, NSTimeInterval duration, NSTimeInterval delay, NSUInteger options, void *anim, void *completion",
     "accel(duration), delay, options, anim, completion"),
    ("animateKeyframesWithDuration:delay:options:animations:completion:",
     "void(*)(id,SEL,NSTimeInterval,NSTimeInterval,NSUInteger,void*,void*)",
     "id self, SEL _cmd, NSTimeInterval duration, NSTimeInterval delay, NSUInteger options, void *anim, void *completion",
     "accel(duration), delay, options, anim, completion"),
]

for i, (sel, sig, params, args) in enumerate(SIGS):
    out.append("static IMP _lanim_orig_%d = NULL;" % i)
    out.append("__attribute__((unused)) static void _lanim_%d(%s) {" % (i, params))
    out.append("    if (!_lanim_orig_%d) return;" % i)
    out.append("    ((%s)_lanim_orig_%d)(self, _cmd, %s);" % (sig, i, args))
    out.append("}")
    out.append("")

INSTALL = [
    ("animateWithDuration:animations:", 0),
    ("animateWithDuration:animations:completion:", 1),
    ("animateWithDuration:delay:options:animations:completion:", 2),
    ("animateKeyframesWithDuration:delay:options:animations:completion:", 3),
]

out.append("static int installLaunchSpeedupHooksImpl(void) {")
out.append("    if (!gLaunchSpeedup || gSafeMode) return 0;")
out.append('    Class uiv = objc_getClass("UIView");')
out.append("    if (!uiv) return 0;")
out.append("    // ★ 这四个是【类方法】（UIView.h 里全是 + 号），必须 hook 元类。")
out.append("    //   1.0.7~1.0.9 传的是 uiv（类对象）→ MSHookMessageEx 当成实例方法处理，")
out.append("    //   而 UIView 上没有同名实例方法 → 挂到不存在的位置，SpringBoard 随后崩溃。")
out.append("    Class meta = object_getClass((id)uiv);")
out.append("    if (!meta) return 0;")
out.append("    int n = 0;")
for sel, idx in INSTALL:
    out.append("    {")
    out.append('        SEL s = sel_registerName("%s");' % sel)
    out.append("        if ([uiv respondsToSelector:s]) {")   # 类方法存在性，正确
    out.append("            MSHookMessageEx(meta, s, (IMP)_lanim_%d, &_lanim_orig_%d);" % (idx, idx))
    out.append("            if (_lanim_orig_%d) { n++; }" % idx)   # 只有拿到 orig 才算成功
    out.append('            rawLog("launch-hook: UIView(class) :: %s orig=%%p", (void *)_lanim_orig_%d);' % (sel, idx))
    out.append("        }")
    out.append("    }")
out.append("    return n;")
out.append("}")
out.append("")

print("\n".join(out))

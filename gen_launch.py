#!/usr/bin/env python3
# Generates LaunchSpeedup.inc — per-hook functions + guarded MSHookMessageEx installer.
# Each candidate gets its OWN captured orig IMP (no cross-class recursion when a hooked
# subclass super-calls a hooked parent). Installation is guarded by class existence AND
# instancesRespondToSelector, so selectors that don't exist on this iOS version are skipped
# (never added as spurious methods).

CANDIDATES = [
    # (className, selectorString, hasArg)
    # App-open / launch animation
    ("SBAppLaunchAnimationController",            "animationDuration",            False),
    ("SBAppLaunchAnimationController",            "duration",                     False),
    ("SBAppLaunchAnimationController",            "_duration",                    False),
    # Generic app transition (open/close)
    ("SBAppTransition",                           "duration",                     False),
    ("SBAppTransition",                           "_completionDuration",          False),
    ("SBAppTransition",                           "completionDuration",           False),
    ("SBAppTransition",                           "_completionDurationForContext:", True),
    # Open: app<->app
    ("SBAppToAppWorkspaceTransaction",            "completionDuration",           False),
    ("SBAppToAppWorkspaceTransaction",            "_completionDurationForContext:", True),
    ("SBAppToAppWorkspaceTransaction",            "duration",                     False),
    # Close: app->home
    ("SBAppToHomeWorkspaceTransaction",           "completionDuration",           False),
    ("SBAppToHomeWorkspaceTransaction",           "_completionDurationForContext:", True),
    ("SBAppToHomeWorkspaceTransaction",           "duration",                     False),
    # Activate / deactivate workspace transactions
    ("SBAppActivationWorkspaceTransaction",       "_completionDurationForContext:", True),
    ("SBAppActivationWorkspaceTransaction",       "completionDuration",           False),
    ("SBAppDeactivationWorkspaceTransaction",     "_completionDurationForContext:", True),
    ("SBAppDeactivationWorkspaceTransaction",     "completionDuration",           False),
    # Legacy names (older iOS)
    ("SBApplicationLaunchTransition",             "duration",                     False),
    ("SBAppLaunchTransition",                     "duration",                     False),
]

def fname(i):
    return "_lhook_%d" % i

out = []
out.append("// AUTO-GENERATED by gen_launch.py — do not edit.")
out.append("#import <objc/runtime.h>")
out.append("#import <objc/message.h>")
out.append("")
out.append("extern void MSHookMessageEx(Class _cls, SEL _sel, IMP _new, IMP *_orig);")
out.append("")
# per-hook orig vars + functions
for i, (cls, sel, hasArg) in enumerate(CANDIDATES):
    fn = fname(i)
    out.append("static IMP _orig_%d = NULL;" % i)
    if hasArg:
        out.append("static double %s(id self, SEL _cmd, id ctx) {" % fn)
        out.append("    double d = _orig_%d ? ((double(*)(id,SEL,id))_orig_%d)(self,_cmd,ctx) : 0.0;" % (i, i))
    else:
        out.append("static double %s(id self, SEL _cmd) {" % fn)
        out.append("    double d = _orig_%d ? ((double(*)(id,SEL))_orig_%d)(self,_cmd) : 0.0;" % (i, i))
    out.append("    if (gLaunchSpeedup && d > 0.0 && gLaunchDivisor > 0.0) d /= gLaunchDivisor;")
    out.append("    return d;")
    out.append("}")
    out.append("")

# installer
out.append("static int installLaunchSpeedupHooks(void) {")
out.append("    if (!gLaunchSpeedup) return 0;")
out.append("    int n = 0;")
for i, (cls, sel, hasArg) in enumerate(CANDIDATES):
    fn = fname(i)
    out.append("    {")
    out.append('        Class c = objc_getClass("%s");' % cls)
    out.append('        SEL s = sel_registerName("%s");' % sel)
    out.append("        if (c && [c instancesRespondToSelector:s]) {")
    out.append("            MSHookMessageEx(c, s, (IMP)%s, &_orig_%d);" % (fn, i))
    out.append("            n++;")
    out.append('            rawLog("launch-hook: %s :: %s (divisor=%%.1f)", gLaunchDivisor);' % (cls, sel))
    out.append("        }")
    out.append("    }")
out.append("    return n;")
out.append("}")

print("\n".join(out))

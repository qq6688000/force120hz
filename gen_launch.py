#!/usr/bin/env python3
"""生成 LaunchSpeedup.inc —— 启动动画加速（CAAnimation setDuration 方案）。

=============================================================================
三次尝试的实测结论，避免以后再走弯路：

尝试 1：hook SB 私有类的 duration 方法
  SBAppLaunchAnimationController / SBAppTransition / SBAppTo*WorkspaceTransaction
  → 1.0.6 运行时探测扫了全部 90071 个已注册类，SBApp* / SBApplication* 前缀下
    **0 个** 类带 duration / completionDuration / animationDuration。类名已失效。

尝试 2：hook UIView 的类方法 +animateWithDuration:animations: 等 4 个
  → 1.0.7~1.0.9 传的是类对象而非元类，MSHookMessageEx 当成实例方法处理，
    而 UIView 没有同名实例方法 → 挂到不存在的位置，实际 no-op（所以显示
    launch-hooks=4 却不崩，是假成功）。
  → 1.1.0 用 object_getClass 拿到元类正确挂载后 → **SpringBoard 每 10 秒崩溃
    重启一次**（日志 pid=6201 → 6238，launch-hooks 永远 -1）。
  → 结论：UIView 的动画类方法是 SpringBoard 里每一个动画的入口，无法安全限定
    作用域。永久放弃。

尝试 3（当前）：hook -[CAAnimation setDuration:]（CAMediaTiming.h:43）
  · 类型 CFTimeInterval = double，单个标量参数，ABI 最简单
  · 只改「这个动画播多久」，不改变动画由谁发起、何时发起
  · CAAnimation 是公开类，setDuration: 是 CAMediaTiming 协议的公开属性
  · 是【实例方法】，所以 MSHookMessageEx 的目标就是类对象本身（不是元类）

安全设计：
  1. isSB() 守卫 —— 不影响任何 App 自己的动画
  2. 低于 0.12 秒的不加速（按钮反馈除以 5 会闪烁）
  3. 用 instancesRespondToSelector: 检查，口径与 MSHookMessageEx 的挂载目标一致
     （1.0.7 的假成功就是因为检查类方法、挂实例方法，两边口径不一致）

★ 注意：Logos 不处理 #include 进来的文件，所以这里不能用 %hook，
  必须手写 MSHookMessageEx trampoline。
=============================================================================
"""

HEADER = """// AUTO-GENERATED by gen_launch.py — do not edit.
// 启动动画加速：hook -[CAAnimation setDuration:]（CFTimeInterval 标量，实例方法）。
// 仅作用于 SpringBoard；短动画不加速。
"""

BODY = r"""// 低于此值的动画不加速（按钮反馈、点击高亮等短动画）
#define kMinAccelDuration 0.12

// 加速应用：只改时长，不改其它任何东西
static CFTimeInterval f120Accel(CFTimeInterval d) {
    // ★ 只作用于 SpringBoard。不加这行会把所有 App 的所有动画都改掉。
    if (!isSB()) return d;
    if (!gLaunchSpeedup || gSafeMode) return d;
    if (d < kMinAccelDuration) return d;
    if (gLaunchDivisor <= 1.0) return d;
    if (gLaunchDivisor > 30.0) gLaunchDivisor = 30.0;
    return d / gLaunchDivisor;
}

// -[CAAnimation setDuration:]  —— 实例方法，类对象即挂载目标
static IMP f120_orig_setDuration = NULL;
static void f120_setDuration(id self, SEL _cmd, CFTimeInterval duration) {
    if (!f120_orig_setDuration) return;   // 理论上不会发生，防御
    ((void (*)(id, SEL, CFTimeInterval))f120_orig_setDuration)(self, _cmd, f120Accel(duration));
}

static int installLaunchSpeedupHooksImpl(void) {
    if (!gLaunchSpeedup || gSafeMode) return 0;
    if (!isSB()) return 0;                        // 只装在 SpringBoard

    Class ca = objc_getClass("CAAnimation");
    if (!ca) { rawLog("launch-speedup: CAAnimation not found"); return 0; }

    SEL s = sel_registerName("setDuration:");
    // ★ 用 instancesRespondToSelector: —— setDuration: 是实例方法，
    //   检查口径必须和 MSHookMessageEx 的目标一致（1.0.7 就是这里错了）。
    if (![ca instancesRespondToSelector:s]) {
        rawLog("launch-speedup: CAAnimation has no setDuration: — abort");
        return 0;
    }

    MSHookMessageEx(ca, s, (IMP)f120_setDuration, &f120_orig_setDuration);
    if (!f120_orig_setDuration) {
        rawLog("launch-speedup: hook failed (orig is NULL)");
        return 0;
    }
    rawLog("launch-speedup: CAAnimation setDuration: hooked, orig=%p divisor=%.1f",
           (void *)f120_orig_setDuration, gLaunchDivisor);
    return 1;
}
"""

print(HEADER + BODY)
